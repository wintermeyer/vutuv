// Every emoji in one flat list, in group order: [char, codes, group, haystack].
// The haystack is what search matches against — the shortcodes plus BOTH
// languages' keywords, so a German and an English member find the same emoji
// whichever language the interface is in.
export const EMOJI_LIST = Object.entries(EMOJI_GROUPS).flatMap(([group, entries]) =>
  entries.map(([char, codes, en, de]) => ({
    char,
    codes: codes.split(" ").filter(Boolean),
    group,
    haystack: `${codes} ${en} ${de}`.toLowerCase(),
  }))
)

// shortcode (and alias) -> character, for the type-through. First writer wins, so
// a duplicate alias further down the file can never shadow an earlier canonical
// name.
const BY_CODE = new Map()

for (const entry of EMOJI_LIST) {
  for (const code of entry.codes) {
    if (!BY_CODE.has(code)) BY_CODE.set(code, entry.char)
  }
}

export const emojiForShortcode = (code) => BY_CODE.get(code.toLowerCase()) || null

// The `:name:` run immediately before the caret. Anchored at the end so it only
// ever fires on the colon the member just typed, and deliberately strict about
// the charset (`a-z0-9_+-`), so prose like "Achtung: 10:30" cannot match.
export const SHORTCODE_AT_CARET = /:([a-z0-9_+-]{1,32}):$/i

// Search: every whitespace-separated token must appear in the entry's haystack,
// so "grün herz" finds 💚 and "green heart" does too. An empty query returns the
// group unfiltered.
//
// Matching is by SUBSTRING, on purpose: German compounds mean "blume" has to find
// "sonnenblume" and "herz" has to find "herzen". The cost is the odd mid-word
// hit — "herz" also sits inside "scherz", so 😉 matches — so results are RANKED,
// with the emoji whose words *begin* with the query first. Both stay findable;
// only the order says which is likely meant.
const escapeForRegex = (token) => token.replace(/[.*+?^${}()|[\]\\-]/g, "\\$&")

const wordStartMatchers = (tokens) =>
  tokens.map((token) => new RegExp(`(^|\\s)${escapeForRegex(token)}`))

export const searchEmoji = (query, group) => {
  const tokens = query.trim().toLowerCase().split(/\s+/).filter(Boolean)
  if (tokens.length === 0) {
    return EMOJI_LIST.filter((entry) => entry.group === group)
  }

  const matchers = wordStartMatchers(tokens)

  return EMOJI_LIST.filter((entry) => tokens.every((token) => entry.haystack.includes(token)))
    .map((entry) => ({
      entry,
      score: matchers.filter((matcher) => matcher.test(entry.haystack)).length,
    }))
    // Descending by how many tokens matched a whole word's start. Array.sort is
    // stable in every browser we support, so equal scores keep the dataset's
    // own order (canonical emoji before the variations that follow it).
    .sort((a, b) => b.score - a.score)
    .map(({ entry }) => entry)
}
